import { DEFAULT_LOOK, MODES, REACHES, THEMES, type Mode } from "./look";
import {
  adjustments,
  baseTokens,
  chromeTokens,
  classicDots,
  dotTokens,
  reachTokens,
  resetTokens,
  unreachable,
  type Tokens,
} from "./tokens";

function block(selector: string, tokens: Tokens, scheme?: Mode): string {
  const lines = Object.entries(tokens).map(([k, v]) => `  ${k}: ${v};`);
  if (scheme) lines.unshift(`  color-scheme: ${scheme};`);
  return `${selector} {\n${lines.join("\n")}\n}\n`;
}

const tm = (theme: string, mode: Mode) =>
  `[data-theme="${theme}"][data-mode="${mode}"]`;

/** The whole of themes.generated.css. */
export function renderCss(): string {
  const out: string[] = [
    "/* Generated by web/src/theme/css.ts from themes.json. Do not edit by hand:\n" +
      "   run `pnpm --filter @hive-mind/web themes` and commit the result. */\n",
  ];
  const { theme: dt, mode: dm, reach: dr, dots: dd } = DEFAULT_LOOK;
  out.push(
    block(
      ":root",
      {
        ...baseTokens(dt, dm),
        ...reachTokens(dt, dm, dr),
        ...dotTokens(dt, dm, dd),
      },
      dm,
    ),
  );
  for (const t of THEMES)
    for (const m of MODES) out.push(block(tm(t.id, m), baseTokens(t.id, m), m));
  for (const t of THEMES)
    for (const m of MODES)
      for (const r of REACHES)
        out.push(
          block(`${tm(t.id, m)}[data-reach="${r}"]`, reachTokens(t.id, m, r)),
        );
  for (const t of THEMES)
    for (const m of MODES)
      out.push(
        block(`${tm(t.id, m)}[data-dots="theme"]`, dotTokens(t.id, m, "theme")),
      );
  for (const m of MODES) {
    const raw = classicDots(m);
    out.push(block(`[data-mode="${m}"][data-dots="classic"]`, raw));
    // A Classic colour adjusted for one theme's card overrides the fixed eight (higher specificity).
    for (const t of THEMES) {
      const final = dotTokens(t.id, m, "classic");
      const moved = Object.fromEntries(
        Object.entries(final).filter(([k, v]) => raw[k] !== v),
      );
      if (Object.keys(moved).length)
        out.push(block(`${tm(t.id, m)}[data-dots="classic"]`, moved));
    }
  }
  for (const t of THEMES)
    out.push(
      block(
        `${tm(t.id, "light")} [data-scope="chrome"]`,
        chromeTokens(t.id, "light"),
      ),
    );
  for (const t of THEMES)
    for (const m of MODES)
      out.push(
        block(`${tm(t.id, m)} [data-scope="reset"]`, resetTokens(t.id, m)),
      );
  return out.join("");
}

/** The whole of adjustments.generated.txt: every lightness adjustment, and any pair that cannot pass. */
export function renderAdjustments(): string {
  const list = adjustments();
  const lines = [
    "Keystone glass: contrast adjustments (generated by web/src/theme/css.ts; do not edit).",
    "Each line: theme mode reach token from -> to. Seeds and backgrounds are never adjusted.",
    `${list.length} adjustments.`,
    "",
    ...list.map(
      (a) => `${a.theme} ${a.mode} ${a.reach} ${a.token} ${a.from} -> ${a.to}`,
    ),
  ];
  const stuck = unreachable();
  if (stuck.length) {
    lines.push("", `${stuck.length} pairs cannot pass by lightness alone:`, "");
    for (const u of stuck)
      lines.push(
        `${u.theme} ${u.mode} ${u.token} ${u.value} (min ${u.min}): best ${u.best.value} reaches ${u.best.ratio.toFixed(2)} on ${u.best.against}; below the minimum on: ${u.failing.join(", ")}`,
      );
  }
  return lines.join("\n") + "\n";
}
