#!/usr/bin/env node
// The remote connector (an Edge Function) cannot import from mcp/, so it gets
// a copy of the shared tools file. This writes that copy:
//
//   node scripts/sync-connector-tools.mjs           write the copy
//   node scripts/sync-connector-tools.mjs --check   exit 1 if it is out of date
//
// The copy is the source byte for byte under a header. Its bare imports stay
// as they are; supabase/functions/mcp/deno.json maps them for the Edge runtime.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const SOURCE = "mcp/src/tools.ts";
const COPY = "supabase/functions/mcp/tools.ts";

const HEADER =
  "// GENERATED by scripts/sync-connector-tools.mjs: do not edit this file,\n" +
  "// edit mcp/src/tools.ts and run `pnpm sync:tools`.\n" +
  "//\n";

const path = (relative) =>
  fileURLToPath(new URL(`../${relative}`, import.meta.url));

const wanted = HEADER + readFileSync(path(SOURCE), "utf8");

if (process.argv.includes("--check")) {
  let current = null;
  try {
    current = readFileSync(path(COPY), "utf8");
  } catch {
    // A missing copy is an out-of-date copy.
  }
  if (current !== wanted) {
    console.error(
      `${COPY} is not the copy of ${SOURCE}. Run \`pnpm sync:tools\`.`,
    );
    process.exit(1);
  }
} else {
  writeFileSync(path(COPY), wanted);
  console.log(`${COPY} written from ${SOURCE}.`);
}
